def main() -> None:
    global RESULTS_DIR, RESULTS_NON_UAT_DIR, MODELS_DIR, PASO_6_PATH, WATERFALL_PATH
    parser = argparse.ArgumentParser(
        description="Phase 11b+ — Process returned pm_report chunks with steward decisions"
    )
    parser.add_argument(
        "--input-dir",
        default=None,
        help="Input directory (default: uat/non_uat_decisions/)",
    )
    parser.add_argument(
        "--countries",
        nargs="*",
        default=None,
        help="ISO codes to process (e.g. DE HK TR). Default: all eligible.",
    )
    parser.add_argument("--dry-run", action="store_true")
    # Path overrides for Dataiku managed folder compatibility (P0.3)
    parser.add_argument(
        "--results-dir",
        default=None,
        help="Override blind_uat results dir (default: uat/results/)",
    )
    parser.add_argument(
        "--results-non-uat-dir",
        default=None,
        help="Override non-UAT results dir (default: uat/results_non_uat/)",
    )
    parser.add_argument("--models-dir", default=None, help="Override models dir (default: models/)")
    parser.add_argument(
        "--manifest-dir",
        default=None,
        help="Override manifest dir, for the reconciliation waterfall CSV (default: uat/manifest/)",
    )
    args = parser.parse_args()

    # Reassign module-level path constants in place so every existing helper
    # (which reads these as bare globals) transparently picks up the override.
    if args.results_dir:
        RESULTS_DIR = Path(args.results_dir)
    if args.results_non_uat_dir:
        RESULTS_NON_UAT_DIR = Path(args.results_non_uat_dir)
    if args.models_dir:
        MODELS_DIR = Path(args.models_dir)
        PASO_6_PATH = MODELS_DIR / "paso_6_model_strategy_decision.json"
    if args.manifest_dir:
        WATERFALL_PATH = Path(args.manifest_dir) / "reconciliation_waterfall.csv"

    input_dir = Path(args.input_dir) if args.input_dir else NON_UAT_DECISIONS_DIR
    if not input_dir.exists():
        logger.error("Input directory not found: %s", input_dir)
        sys.exit(1)

    paso6 = _load_paso6()
    groups = _discover_pm_report_files(input_dir)

    if not groups:
        logger.error("No pm_report chunk files found in %s", input_dir)
        sys.exit(1)

    # Filter by --countries if provided
    if args.countries:
        wanted_iso = {c.strip().upper() for c in args.countries}
        groups = {k: v for k, v in groups.items() if k[0] in wanted_iso}
        if not groups:
            logger.error("None of the requested countries found in pm_report files")
            sys.exit(1)

    logger.info("Markets to process (%d groups): %s", len(groups), sorted(k[0] for k in groups))

    errors: List[str] = []
    for (iso, ts), paths in sorted(groups.items()):
        slug = ISO_TO_SLUG.get(iso, iso.lower())
        try:
            process_market(iso, ts, paths, paso6, args.dry_run)
        except Exception as exc:
            logger.error("[%s] FAILED: %s", slug, exc, exc_info=True)
            errors.append(slug)

    if errors:
        logger.warning("Failed/skipped countries: %s", errors)
        sys.exit(1)
    else:
        logger.info("All pm_report decision files processed successfully.")


if __name__ == "__main__":
    main()

def process_market(
    iso: str,
    ts: str,
    chunk_paths: List[Path],
    paso6: Dict,
    dry_run: bool,
) -> None:
    slug = ISO_TO_SLUG[iso]
    logger.info("[%s] Processing %d chunk(s) (ts=%s)", slug, len(chunk_paths), ts)

    # Operational PM Reports Slice: INGESTED_FILE_REGISTRY hash-based idempotency
    # (dataiku_migration/design/recipe_ingest_steward_decisions.design.md)
    ingestion_run_id = f"{slug}_nonuat_{ts}"
    try:
        from src.lineage.pair_registry import PairRegistry

        registry = PairRegistry(ROOT / "data" / "lineage")
    except Exception as _exc:
        logger.warning("[%s] PairRegistry unavailable for file-registry tracking: %s", slug, _exc)
        registry = None

    # Aggregate DSR_DECISION from all sets
    decision_frames: List[pd.DataFrame] = []
    raw_frames: List[pd.DataFrame] = []
    # (file_hash, result_dict) pairs — SUCCESS is only committed once the whole (iso, ts) group
    # durably completes (IMPLEMENTATION_REVIEW finding F1); never mark a file SUCCESS while a
    # later file in the same group could still fail and abort the group's write.
    pending_file_success: List[Tuple[str, Dict]] = []

    # Reconciliation waterfall counters (Phase 1, 2026-09-15 UAT methodology audit plan)
    files_discovered = len(chunk_paths)
    files_processed = 0
    files_already_processed = 0
    raw_rows_total = 0
    rows_with_decision_total = 0
    automated_excluded_total = 0
    independently_reviewed_total = 0

    for path in sorted(chunk_paths):
        logger.info("  [%s] Reading: %s", slug, path.name)

        file_hash = None
        if registry is not None and not dry_run:
            try:
                file_hash = _sha256_file(path)
                existing_entry = registry.get_file_registry_entry(file_hash)
                if existing_entry and existing_entry.get("status") == "SUCCESS":
                    logger.info(
                        "  [%s] Skipping %s — already ingested (hash=%s, matches %s)",
                        slug,
                        path.name,
                        file_hash[:12],
                        existing_entry.get("file_name"),
                    )
                    files_already_processed += 1
                    continue
                registry.record_ingested_file_start(
                    file_hash=file_hash,
                    file_name=path.name,
                    file_path=str(path),
                    market_iso=iso,
                    ingestion_run_id=ingestion_run_id,
                )
            except Exception as _exc:
                logger.warning(
                    "  [%s] File-registry hash check skipped for %s: %s", slug, path.name, _exc
                )

        try:
            df_chunk = pd.read_excel(
                path, sheet_name=0, engine="openpyxl"
            )  # stewards rename PM_Records to Sheet1 on save
        except Exception as exc:
            logger.warning("  [%s] Cannot read PM_Records from %s: %s", slug, path.name, exc)
            if registry is not None and file_hash:
                registry.record_ingested_file_result(
                    file_hash, {"status": "FAILED", "error_message": str(exc)}
                )
            continue

        # Blindness check (RULE-002)
        try:
            _check_blindness(df_chunk, slug)
        except Exception as exc:
            if registry is not None and file_hash:
                registry.record_ingested_file_result(
                    file_hash,
                    {"status": "FAILED", "error_message": str(exc), "raw_rows": len(df_chunk)},
                )
            raise

        if "pair_id" not in df_chunk.columns:
            logger.warning("  [%s] pair_id column missing in %s — skipping", slug, path.name)
            if registry is not None and file_hash:
                registry.record_ingested_file_result(
                    file_hash,
                    {
                        "status": "FAILED",
                        "error_message": "pair_id column missing",
                        "raw_rows": len(df_chunk),
                    },
                )
            continue

        # FAILURE-019 fix: prefer the genuine steward decision column; DSR_DECISION alone
        # (used by legacy pre-v2.7.3 files) is the fallback when the newer column is absent.
        if SYSTEM_LABEL_COL in df_chunk.columns:
            resolved_decision = df_chunk[SYSTEM_LABEL_COL]
        elif "DSR_DECISION" in df_chunk.columns:
            resolved_decision = df_chunk["DSR_DECISION"]
        else:
            logger.warning(
                "  [%s] Neither '%s' nor 'DSR_DECISION' present in %s — skipping",
                slug,
                SYSTEM_LABEL_COL,
                path.name,
            )
            if registry is not None and file_hash:
                registry.record_ingested_file_result(
                    file_hash,
                    {
                        "status": "FAILED",
                        "error_message": "no decision column present",
                        "raw_rows": len(df_chunk),
                    },
                )
            continue

        # RULE-026 traceability: track whether this row's decision came from the genuine
        # steward column (HUMAN) or the legacy DSR_DECISION-only fallback (LEGACY_DSR_FALLBACK)
        review_source_value = (
            "HUMAN" if SYSTEM_LABEL_COL in df_chunk.columns else "LEGACY_DSR_FALLBACK"
        )

        df_chunk = df_chunk.copy()
        df_chunk["_resolved_decision"] = resolved_decision
        df_chunk["_review_source"] = review_source_value

        # Keep only rows with a filled decision
        filled = df_chunk[
            df_chunk["_resolved_decision"].notna()
            & (df_chunk["_resolved_decision"].astype(str).str.strip() != "")
        ].copy()

        # FAILURE-019 circularity guard: an AUTOMATED passthrough is not an independent
        # human review, regardless of which column it landed in — exclude unconditionally.
        if "DECISION_SOURCE" in filled.columns:
            n_before_auto_filter = len(filled)
            filled = filled[filled["DECISION_SOURCE"] != "AUTOMATED"]
            n_automated_excluded = n_before_auto_filter - len(filled)
        else:
            n_before_auto_filter = len(filled)
            n_automated_excluded = 0

        logger.info(
            "  [%s] %s: %d rows, %d independently-reviewed decisions (%d AUTOMATED excluded)",
            slug,
            path.name,
            len(df_chunk),
            len(filled),
            n_automated_excluded,
        )

        files_processed += 1
        raw_rows_total += len(df_chunk)
        rows_with_decision_total += n_before_auto_filter
        automated_excluded_total += n_automated_excluded
        independently_reviewed_total += len(filled)

        if registry is not None and file_hash:
            # Group-level dedup/anti-join/conflict counts (duplicates_within_file,
            # duplicates_across_files, already_resolved, new_resolved_pairs, conflicting_decisions)
            # are only knowable after aggregating this whole (iso, ts) group — they are captured
            # in RECONCILIATION_WATERFALL below, not here (INGESTED_FILE_REGISTRY.schema.yaml
            # documents these fields as group-level-only; they remain 0 at the per-file grain).
            # SUCCESS itself is NOT committed here — only queued — until the group durably
            # completes (see pending_file_success commit points below; F1 fix).
            pending_file_success.append(
                (
                    file_hash,
                    {
                        "raw_rows": len(df_chunk),
                        "rows_with_decision": n_before_auto_filter,
                        "automated_rows_excluded": n_automated_excluded,
                    },
                )
            )

        decision_frames.append(
            filled[["pair_id", "_resolved_decision", "_review_source"]].rename(
                columns={"_resolved_decision": "DSR_DECISION"}
            )
        )
        # Keep all columns for scoring (drop decision/source columns so Predictor won't reject them)
        raw_frames.append(
            filled.drop(
                columns=["_resolved_decision", "DSR_DECISION", SYSTEM_LABEL_COL, "_review_source"],
                errors="ignore",
            )
        )

    if not decision_frames:
        logger.warning("[%s] No filled decisions found across all chunks", slug)
        if not dry_run:
            _commit_pending_file_success(registry, pending_file_success)
            _append_waterfall_record(
                {
                    "run_timestamp": datetime.now(timezone.utc).isoformat(),
                    "country": slug,
                    "iso": iso,
                    "file_group_ts": ts,
                    "source_type": SOURCE,
                    "files_discovered": files_discovered,
                    "files_processed": files_processed,
                    "files_already_processed": files_already_processed,
                    "files_skipped": files_discovered - files_processed - files_already_processed,
                    "raw_rows": raw_rows_total,
                    "rows_with_decision": 0,
                    "automated_prefill_excluded": 0,
                    "independently_reviewed_rows": 0,
                    "duplicate_rows_removed_at_aggregation": 0,
                    "already_resolved_removed": 0,
                    "eligible_evidence_rows": 0,
                    "exclusion_reason": "no_filled_decisions_in_any_chunk",
                }
            )
        return

    # Concatenate and dedup by pair_id (keep first occurrence across sets — combines
    # within-file and cross-file duplicates; not split further, documented limitation)
    decisions_df = pd.concat(decision_frames, ignore_index=True)
    rows_before_dedup = len(decisions_df)
    decisions_df = decisions_df.drop_duplicates(subset=["pair_id"], keep="first")
    duplicate_rows_removed = rows_before_dedup - len(decisions_df)
    raw_df = pd.concat(raw_frames, ignore_index=True).drop_duplicates(
        subset=["pair_id"], keep="first"
    )
    logger.info("[%s] Aggregated: %d unique pair_ids with decisions", slug, len(decisions_df))

    # Anti-join: remove pairs already resolved in blind_uat or prior blind_non_uat
    resolved_ids = _load_resolved_pair_ids(slug)
    before = len(decisions_df)
    decisions_df = decisions_df[~decisions_df["pair_id"].isin(resolved_ids)]
    raw_df = raw_df[raw_df["pair_id"].isin(decisions_df["pair_id"])]
    already_resolved_removed = before - len(decisions_df)
    logger.info(
        "[%s] After anti-join: %d new pair_ids (%d removed)",
        slug,
        len(decisions_df),
        already_resolved_removed,
    )

    if len(decisions_df) == 0:
        logger.info("[%s] All pairs already resolved — nothing to write", slug)
        if not dry_run:
            _commit_pending_file_success(registry, pending_file_success)
            _append_waterfall_record(
                {
                    "run_timestamp": datetime.now(timezone.utc).isoformat(),
                    "country": slug,
                    "iso": iso,
                    "file_group_ts": ts,
                    "source_type": SOURCE,
                    "files_discovered": files_discovered,
                    "files_processed": files_processed,
                    "files_already_processed": files_already_processed,
                    "files_skipped": files_discovered - files_processed - files_already_processed,
                    "raw_rows": raw_rows_total,
                    "rows_with_decision": rows_with_decision_total,
                    "automated_prefill_excluded": automated_excluded_total,
                    "independently_reviewed_rows": independently_reviewed_total,
                    "duplicate_rows_removed_at_aggregation": duplicate_rows_removed,
                    "already_resolved_removed": already_resolved_removed,
                    "eligible_evidence_rows": 0,
                    "exclusion_reason": "all_pairs_already_resolved",
                }
            )
        return

    # Normalize decisions via canonical normalize_target() (RULE-012 / FAILURE-004)
    # Pre-normalize variant spellings not covered by normalize_target ('Match' = Merge synonym)
    _DSR_ALIASES = {"match": "Merge", "matched": "Merge", "no match": "No Merge"}
    decisions_df = decisions_df.copy()
    decisions_df["DSR_DECISION"] = (
        decisions_df["DSR_DECISION"]
        .astype(str)
        .str.strip()
        .apply(lambda v: _DSR_ALIASES.get(v.lower(), v))
    )
    decisions_df["steward_label"] = _normalize_decision(decisions_df["DSR_DECISION"])
    decisions_df["steward_decision"] = decisions_df["DSR_DECISION"]

    # Score with frozen RF model via Predictor (RULE-011)
    entry = paso6.get(slug, {})
    decision_strategy = entry.get("decision", "GLOBAL")
    threshold = float(entry.get("threshold_optimal", {}).get("threshold_merge", 0.5))

    strategy_lower = decision_strategy.lower()
    if strategy_lower == "evaluate":
        custom_path = MODELS_DIR / f"model_custom_{slug}.pkl"
        strategy_lower = "custom" if custom_path.exists() else "global"

    model_file = f"model_custom_{slug}.pkl" if strategy_lower == "custom" else "model_global.pkl"
    model_path = MODELS_DIR / model_file
    model_version = model_path.name if model_path.exists() else "global_fallback"
    # Phase 3 (model-version evidence segregation): filename alone doesn't change across
    # retrains, so also capture the content hash — the true "materially different model"
    # identity used by uat_04/uat_06's drift guard (_check_model_drift).
    model_file_sha256 = _sha256_file(model_path) if model_path.exists() else None

    if slug not in paso6:
        logger.warning(
            "[%s] Not registered in paso_6_model_strategy_decision.json — "
            "using GLOBAL model as fallback (RULE-017)",
            slug,
        )

    logger.info(
        "[%s] Scoring — strategy=%s threshold=%.3f model=%s",
        slug,
        strategy_lower,
        threshold,
        model_file,
    )

    if dry_run:
        raw_df["prob_merge"] = np.random.default_rng(42).uniform(0, 1, len(raw_df))
        raw_df["predicted_class"] = (raw_df["prob_merge"] >= threshold).map(
            {True: "MERGE", False: "NO_MERGE"}
        )
    else:
        from src.inference.predictor import Predictor

        predictor = Predictor(
            base_dir=ROOT,
            strategy=strategy_lower,
            enable_rules=False,
            enable_tree_explainability_metrics=False,
        )

        with tempfile.TemporaryDirectory() as tmpdir:
            tmp_path = Path(tmpdir) / f"{slug}_score_input.xlsx"
            raw_df.to_excel(tmp_path, index=False, engine="openpyxl")
            output_df, _ = predictor.predict(input_path=tmp_path, country=slug)

        if output_df is None or len(output_df) == 0:
            raise RuntimeError(f"[{slug}] Predictor returned empty output")

        prob_col = next(
            (
                c
                for c in output_df.columns
                if "probability" in c.lower() or "prob_merge" in c.lower()
            ),
            None,
        )
        pred_col = next(
            (c for c in output_df.columns if "prediction" in c.lower() or "predicted" in c.lower()),
            None,
        )
        if prob_col is None or pred_col is None:
            raise RuntimeError(
                f"[{slug}] Cannot locate probability/prediction columns: {list(output_df.columns)}"
            )

        raw_df = raw_df.copy()
        raw_df["prob_merge"] = output_df[prob_col].values
        raw_df["predicted_class"] = output_df[pred_col].values

    raw_df["score_bucket"] = raw_df["prob_merge"].clip(0.0, 1.0).apply(_assign_score_bucket)

    # Preserve original DECISION_SOURCE from the reveal mechanism (FAILURE-018 fix) —
    # lets downstream consumers (uat_10 evidence report) exclude AUTOMATED passthrough
    # rows from independent-review metrics. Blank when the market has no reveal active.
    if "DECISION_SOURCE" in raw_df.columns:
        raw_df["decision_source"] = raw_df["DECISION_SOURCE"].fillna("")
    else:
        raw_df["decision_source"] = ""

    # Join scores back to decisions
    scored = decisions_df.merge(
        raw_df[["pair_id", "prob_merge", "predicted_class", "score_bucket", "decision_source"]],
        on="pair_id",
        how="left",
    )

    # Build output
    df_out = scored[
        [
            "pair_id",
            "steward_decision",
            "steward_label",
            "prob_merge",
            "predicted_class",
            "score_bucket",
            "decision_source",
        ]
    ].copy()
    df_out["source"] = SOURCE
    df_out["phase"] = PHASE
    df_out["model_version"] = model_version
    df_out["model_file_sha256"] = model_file_sha256
    df_out["generation_date"] = date.today().isoformat()
    df_out["country"] = slug

    n_merge = int((df_out["steward_label"] == 1).sum())
    n_no_merge = int((df_out["steward_label"] == 0).sum())
    logger.info(
        "[%s] Ready: %d records (MERGE=%d, NO_MERGE=%d)", slug, len(df_out), n_merge, n_no_merge
    )

    if dry_run:
        logger.info("[%s] [dry-run] output write skipped", slug)
        return

    RESULTS_NON_UAT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = RESULTS_NON_UAT_DIR / f"{slug}_non_uat_results.csv"

    # Append to existing file (preserves prior entries from uat_05 or previous uat_09 runs)
    if out_path.exists():
        existing = pd.read_csv(out_path)
        combined = pd.concat([existing, df_out], ignore_index=True).drop_duplicates(
            subset=["pair_id"], keep="first"
        )
        combined.to_csv(out_path, index=False, encoding="utf-8")
        logger.info(
            "[%s] Appended to %s (%d existing + %d new = %d total)",
            slug,
            out_path.name,
            len(existing),
            len(df_out),
            len(combined),
        )
    else:
        df_out.to_csv(out_path, index=False, encoding="utf-8")
        logger.info("[%s] Written: %s (%d rows)", slug, out_path.name, len(df_out))

    # Lineage: record these as independently-reviewed steward decisions (KNOWN-DEVIATION-003
    # resolution) so future runs' _load_resolved_pair_ids() can find them via the registry.
    try:
        if registry is None:
            from src.lineage.pair_registry import PairRegistry

            registry = PairRegistry(ROOT / "data" / "lineage")
        registry.record_steward_review(
            df_out, uat_run_id=f"{slug}_nonuat_{ts}", decision_source=scored["_review_source"]
        )
    except Exception as _exc:
        logger.warning("[%s] Lineage record_steward_review skipped: %s", slug, _exc)

    # F1 fix: only now — after the results CSV is durably written and steward-review recording
    # has been attempted — commit the queued file-registry SUCCESS entries for this group.
    _commit_pending_file_success(registry, pending_file_success)

    _append_waterfall_record(
        {
            "run_timestamp": datetime.now(timezone.utc).isoformat(),
            "country": slug,
            "iso": iso,
            "file_group_ts": ts,
            "source_type": SOURCE,
            "files_discovered": files_discovered,
            "files_processed": files_processed,
            "files_already_processed": files_already_processed,
            "files_skipped": files_discovered - files_processed - files_already_processed,
            "raw_rows": raw_rows_total,
            "rows_with_decision": rows_with_decision_total,
            "automated_prefill_excluded": automated_excluded_total,
            "independently_reviewed_rows": independently_reviewed_total,
            "duplicate_rows_removed_at_aggregation": duplicate_rows_removed,
            "already_resolved_removed": already_resolved_removed,
            "eligible_evidence_rows": len(df_out),
            "exclusion_reason": "",
        }
    )



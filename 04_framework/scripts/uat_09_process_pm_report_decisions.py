def _load_paso6() -> Dict:
    import json

    with open(PASO_6_PATH, encoding="utf-8") as fh:
        raw = json.load(fh)
    return raw.get("decision", {}).get("by_country", {})


def _sha256_file(path: Path) -> str:
    """Content hash of a model file — the true model-version identity (Phase 3)."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(65536), b""):
            h.update(block)
    return h.hexdigest()


def _check_blindness(df: pd.DataFrame, slug: str) -> None:
    """Raise if any model-output column is detected (RULE-002 enforcement).

    FAILURE-018 fix: files carrying a `DECISION_SOURCE` column went through the
    Decile-Aware Predict Reveal mechanism (ARCHITECTURE v2.7.3) and are sanctioned to
    carry model-output columns (PROB_MERGE/PROB_NO_MERGE/PREDICTION/CONFIDENCE_LEVEL/
    SCORE_BUCKET/AUTOMATION_STATUS, plus adjacent APMU confidence fields) even when
    blank for non-revealed rows. `DECISION_SOURCE` is the unambiguous signature of that
    mechanism — its presence is checked instead of the market's *current* automation
    approval status, which can change between file generation and processing (a market
    approved when the file was generated may since have been reverted to MANUAL with
    more evidence, without the already-generated file's columns becoming a violation
    retroactively). An exact-column allowlist was tried first and abandoned: legitimate
    pre-existing business columns (e.g. apmu_decision_confidence) also match the
    violation patterns, making an allowlist fragile and incomplete in practice.
    """
    if "DECISION_SOURCE" in df.columns:
        logger.info(
            "  [%s] Blindness check skipped — file carries DECISION_SOURCE "
            "(Decile-Aware Predict Reveal, FAILURE-018)",
            slug,
        )
        return
    cols_lower = {c.lower() for c in df.columns}
    violations = [
        pat
        for pat in BLINDNESS_VIOLATION_PATTERNS
        if any(c.startswith(pat) or pat in c for c in cols_lower)
    ]
    if violations:
        raise ValueError(
            f"[{slug}] BLINDNESS VIOLATION in pm_report chunk: {violations}. "
            f"File likely contains model output. Not eligible as blind_non_uat."
        )


def _normalize_decision(series: pd.Series) -> pd.Series:
    """Normalize DSR_DECISION to binary via canonical normalize_target() (RULE-012 / FAILURE-004).

    Pre-processes MDM-specific synonyms not covered by normalize_target():
    'Match'/'match' → 'Merge' (some stewards use this term interchangeably).
    """
    from src.reporting.error_analysis import normalize_target

    # Map MDM synonym before canonical normalization
    cleaned = series.astype(str).str.strip().str.replace(r"^[Mm]atch$", "Merge", regex=True)
    return normalize_target(cleaned)


def _assign_score_bucket(prob: float) -> str:
    b = min(int(math.floor(prob * 10)), 9)
    return f"{b / 10:.1f}–{(b + 1) / 10:.1f}"


def _load_resolved_pair_ids(slug: str) -> Set[str]:
    """
    Load pair_ids already resolved in blind_uat or prior blind_non_uat results.

    KNOWN-DEVIATION-003 RESOLVED: queries PairRegistry.get_resolved_pairs() first
    (populated going forward by uat_00 for blind_uat and by this script for
    blind_non_uat — see the record_steward_review() call in process_market()).
    The direct CSV read is kept as a union, not replaced, because pairs resolved
    before this change was deployed are not retroactively present in the registry.
    """
    resolved: Set[str] = set()
    try:
        from src.lineage.pair_registry import PairRegistry

        registry = PairRegistry(ROOT / "data" / "lineage")
        resolved |= set(registry.get_resolved_pairs(slug))
        logger.info("  [%s] Loaded %d resolved pair_ids from PairRegistry", slug, len(resolved))
    except Exception as exc:
        logger.warning("  [%s] PairRegistry.get_resolved_pairs lookup skipped: %s", slug, exc)
    for results_path in [
        RESULTS_DIR / f"{slug}_steward_results.csv",
        RESULTS_NON_UAT_DIR / f"{slug}_non_uat_results.csv",
    ]:
        if results_path.exists():
            df_r = pd.read_csv(results_path)
            if "pair_id" in df_r.columns:
                resolved |= set(df_r["pair_id"].dropna().astype(str))
                logger.info(
                    "  [%s] Loaded %d resolved pair_ids from %s",
                    slug,
                    len(df_r),
                    results_path.name,
                )
    return resolved


def _append_waterfall_record(record: Dict) -> None:
    """Append one reconciliation-waterfall row (Phase 1, 2026-09-15 UAT methodology audit).

    Never overwrites — this is an evidence trail, not a cache. Safe to call repeatedly;
    each (market, file-group) run adds one row, timestamped, so re-processing history is
    preserved rather than replaced (mirrors the append-only convention of results_non_uat CSVs).
    """
    try:
        WATERFALL_PATH.parent.mkdir(parents=True, exist_ok=True)
        row = pd.DataFrame([record])
        if WATERFALL_PATH.exists():
            existing = pd.read_csv(WATERFALL_PATH)
            combined = pd.concat([existing, row], ignore_index=True)
        else:
            combined = row
        combined.to_csv(WATERFALL_PATH, index=False, encoding="utf-8")
    except Exception as exc:
        logger.warning(
            "  [%s] Reconciliation waterfall record skipped: %s", record.get("country"), exc
        )


def _discover_pm_report_files(
    input_dir: Path,
) -> Dict[Tuple[str, str], List[Path]]:
    """
    Discover pm_report chunk files and group by (iso, timestamp).
    Returns {(iso, timestamp): [sorted paths]}.
    """
    groups: Dict[Tuple[str, str], List[Path]] = {}
    for p in sorted(input_dir.glob("*.xlsx")):
        # Normalise SharePoint suffix from stem before matching
        stem_clean = _SP_SUFFIX_RE.sub("", p.stem)
        # Strip optional "reviewed_" prefix stewards add when returning files (same convention
        # already handled in uat_00_prepare_steward_results.py via removeprefix("reviewed_")).
        stem_clean = re.sub(r"^reviewed_", "", stem_clean, flags=re.IGNORECASE)
        m = PM_REPORT_RE.match(stem_clean)
        if not m:
            continue
        iso = m.group(1)
        ts = m.group(2)
        if iso not in ELIGIBLE_ISO:
            continue
        key = (iso, ts)
        groups.setdefault(key, []).append(p)
    return groups


def _commit_pending_file_success(registry, pending: List[Tuple[str, Dict]]) -> None:
    """Commit queued file-registry SUCCESS results — only call once the (iso, ts) group has
    durably reached a safe terminal state (IMPLEMENTATION_REVIEW finding F1). If the group
    aborts before this is called (e.g. an exception raised earlier in the loop), the queued
    entries are simply never committed and stay at their pre-existing RUNNING/FAILED status,
    so the next run will correctly retry those files instead of silently skipping them."""
    if registry is None:
        return
    for file_hash, result in pending:
        registry.record_ingested_file_result(file_hash, {**result, "status": "SUCCESS"})


